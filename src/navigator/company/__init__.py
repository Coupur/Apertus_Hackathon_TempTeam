"""Company -> what it would ask Bern -> retrieval queries.  Plan: Docs/company_queries_plan.md

  1 collect   name | url | idea -> public pages about the company     (collect.py)
  2 profile   what it does and wants, every item with a quote          (profile.py)
  0 ties      Bern pages that already name the company (name search)   (ties.py)
  3 needs     the resource sections A-M that serve its goals           (needs.py)
  4 queries   per need EN + DE queries in Bern researchers' words      (needs.py)

Output in data/companies/<slug>/: collect.json, profile.json, queries.json (reads as-is with
`navigator retrieve`), report.md.
"""
import json
import re
import unicodedata
from datetime import datetime, timezone
from pathlib import Path

from .. import config
from .collect import collect
from .needs import build_needs, to_queries
from .profile import LIST_FIELDS, build_profile
from .ties import find_ties, format_ties

COMPANIES_DIR = config.DATA_DIR / "companies"


def slug(name: str) -> str:
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()  # Sprüngli -> Sprungli
    return re.sub(r"[^a-z0-9]+", "-", ascii_name.lower()).strip("-")[:40] or "company"


def run(inp: str, kind: str = "auto", max_pages: int = 8, max_needs: int = 8) -> dict:
    col = collect(inp, kind, max_pages)
    profile = build_profile(col)
    ties = find_ties(profile)
    needs = build_needs(profile, max_needs, col["trace"])
    company_id = slug(profile["name"])
    queries = {
        "company_id": company_id,
        "company": {k: profile.get(k) for k in ("name", "website", "summary", "sector", "stage", "in_bern")},
        "generated_by": needs[0]["generated_by"] if needs else profile["generated_by"],
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "ties": ties,  # section 0: Bern pages that already name the company
        "needs": [{k: v for k, v in n.items() if k not in ("en", "de")} for n in needs],
        "queries": to_queries(needs),
    }
    return {"company_id": company_id, "collect": col, "profile": profile, "ties": ties, "needs": needs,
            "queries": queries}


def write(res: dict, out_dir: str | Path | None = None) -> Path:
    out = Path(out_dir) if out_dir else COMPANIES_DIR / res["company_id"]
    out.mkdir(parents=True, exist_ok=True)
    for name, data in (("collect", res["collect"]), ("profile", res["profile"]), ("queries", res["queries"])):
        (out / f"{name}.json").write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    (out / "report.md").write_text(report(res), encoding="utf-8")
    return out


def _cite(item: dict) -> str:
    if not item.get("quote") or item["quote"] == item["value"]:
        return f"[{item['page']}]" if item.get("page") else ""
    return f"“{item['quote']}” [{item['page']}]"


def report(res: dict) -> str:
    p, col, needs = res["profile"], res["collect"], res["needs"]
    bern = {True: "yes", False: "no"}.get(p.get("in_bern"), "unknown")
    lines = [f"# {p['name']}: what they would ask Bern", "",
             f"{p.get('summary', '')}", "",
             f"Input: `{p['input']}` ({p['kind']}) · website: {p.get('website') or '–'} · "
             f"generated by: {res['queries']['generated_by']}", "",
             "## Profile", "",
             "| | |", "|---|---|",
             f"| Sector | {p.get('sector') or '–'} |", f"| Stage | {p.get('stage')} |",
             f"| Locations | {', '.join(p.get('locations', [])) or '–'} |", f"| In Bern | {bern} |",
             f"| Topics (lexicon) | {', '.join(t['label'] for t in p.get('topics', [])) or '–'} |",
             f"| Hiring signal | {'yes' if p.get('hiring') else 'no'} |", ""]
    for field in LIST_FIELDS:
        if p.get(field):
            lines.append(f"**{field.capitalize()}**")
            lines += [f"- {i['value']} {_cite(i)}" for i in p[field]]
            lines.append("")
    if p.get("dropped"):
        lines.append(f"_{len(p['dropped'])} profile items dropped because their quote was not on the page._\n")

    ties = res["ties"]
    lines += ["## 0 · Existing ties in Bern", ""]
    if ties.get("note"):
        lines += [f"_Skipped: {ties['note']}._", ""]
    else:
        lines += [f"{ties['count']} of {ties['pages_searched']} Bern pages name "
                  f"{' / '.join(f'“{t}”' for t in ties['terms'])}.", ""]
        lines += [f"- [{h['title'] or h['url']}]({h['url']}) ({h['source_id']}"
                  f"{', listing page' if h['listing'] else ''}): {h['snippet']}" for h in ties["pages"]]
        lines.append("")

    lines += ["## Questions and queries", ""]
    for n in needs:
        lines += [f"### {n['id']} · {n['section']} {n['section_name']}",
                  f"*{n['basis']} · finds: {n['finds']} · Bern data coverage: {n['coverage']}*", "",
                  f"**Question:** {n['question']}  ", f"**Need:** {n['need']}  ",
                  f"**Based on:** {n['evidence'] or '–'}", ""]
        lines += [f"- `en` {q}" for q in n.get("en", [])] + [f"- `de` {q}" for q in n.get("de", [])]
        if n.get("keywords"):
            lines.append(f"\nKeywords: {', '.join(n['keywords'])}")
        lines.append("")

    lines += ["## Sources", ""] + [f"- [{pg['id']}] {pg['title']}: {pg['url'] or '(input text)'} "
                                   f"({len(pg['text'])} chars)" for pg in col["pages"]]
    lines += ["", "## Trace", ""] + [f"- {t}" for t in col["trace"]]
    return "\n".join(lines) + "\n"


def summary(res: dict) -> str:
    """Short console view: who, then every question with its queries."""
    p = res["profile"]
    out = [f"\n=== {p['name']}  ({p.get('website') or p['kind']})  [{res['queries']['generated_by']}]",
           f"    {p.get('summary', '')[:200]}",
           f"    sector: {p.get('sector') or '-'} | stage: {p.get('stage')} | in Bern: {p.get('in_bern')} | "
           f"topics: {', '.join(t['label'] for t in p.get('topics', [])) or '-'}"]
    for field in ("aspirations", "goals", "wants", "challenges"):
        for i in p.get(field, [])[:2]:
            out.append(f"    {field[:-1] if field.endswith('s') else field:10} {i['value'][:150]}")
    out.append("\n  [0 Existing ties]")
    out.append(format_ties(res["ties"]))
    for n in res["needs"]:
        out.append(f"\n  [{n['id']} {n['section']} {n['section_name']} | {n['basis']} | coverage {n['coverage']}]")
        out.append(f"  Q: {n['question']}")
        for lang in ("en", "de"):
            for q in n.get(lang, []):
                out.append(f"     {lang}  {q}")
    return "\n".join(out)
