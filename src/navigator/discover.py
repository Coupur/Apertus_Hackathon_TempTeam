"""Find *.unibe.ch subdomains that crawled pages link to but that are not a source yet.

Writes src/sources_discovered.json (same format as sources.json), which load_sources() picks up.
A host must be linked from at least `min_links` saved pages, so one-off links are ignored.
Rerun after each crawl: newly crawled sites link to further subdomains.
"""
import json
import re
from collections import Counter

import httpx

from . import config
from .sources import load_sources

HOST_RE = re.compile(r"""href\s*=\s*["']https?://([a-z0-9.-]+\.unibe\.ch)""", re.I)
# portals, not research units (see SKIP_WORDS in crawl.py) and the publication repository (boris.py)
EXCLUDE = {"unibe.ch", "karriere.unibe.ch", "intern.unibe.ch", "ilias.unibe.ch", "teachinghub.unibe.ch",
           "ub.unibe.ch", "edit.cms.unibe.ch", "beratungswegweiser.unibe.ch", "boris.unibe.ch",
           "boris-portal.unibe.ch", "uniaktuell.unibe.ch", "mediarelations.unibe.ch",
           # student and event portals
           "einsteinlectures.unibe.ch", "junioracademics.unibe.ch", "respekt.unibe.ch", "agenda.unibe.ch",
           "studis.unibe.ch", "sub.unibe.ch", "earth-science-master.unibe.ch"}


def _reachable(client: httpx.Client, host: str) -> str | None:
    """UniBE sites mostly live on www.<host>, a few only on the bare host."""
    for url in (f"https://www.{host}/", f"https://{host}/"):
        try:
            if client.get(url).status_code == 200:
                return url
        except httpx.HTTPError:
            pass
    return None


def discover(min_links: int = 5) -> list[dict]:
    known = {s.host for s in load_sources()} - {"unibe.ch"}
    counts: Counter = Counter()
    for page in config.RAW_DIR.glob("*/pages/*.html"):
        html = page.read_text(encoding="utf-8", errors="ignore")
        counts.update({h.lower().removeprefix("www.") for h in HOST_RE.findall(html)})

    found = []
    with httpx.Client(headers={"User-Agent": config.USER_AGENT}, timeout=15, follow_redirects=True) as client:
        for host, n in counts.most_common():
            if n < min_links or host in EXCLUDE or any(host == k or host.endswith("." + k) for k in known):
                continue
            url = _reachable(client, host)
            if not url:
                print(f"  {host:<40} unreachable, skipped")
                continue
            sid = host.removesuffix(".unibe.ch").replace(".", "-")
            found.append({"id": sid, "name": host, "url": url, "institution": "University of Bern",
                          "seed_paths": [], "linked_from_pages": n})
            print(f"  {host:<40} linked from {n:>4} pages -> {url}")
    config.DISCOVERED_SOURCES.write_text(
        json.dumps({"_comment": "Generated by `python -m navigator discover`. Delete entries to skip them.",
                    "sources": found}, indent=1, ensure_ascii=False), encoding="utf-8")
    return found
