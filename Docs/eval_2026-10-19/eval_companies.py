"""Evaluate the company flow end to end on the current index (run from repo root, PYTHONPATH=src).

For every data/companies/<slug>/queries.json given:
  1. Retriever + answers.group_by_need  (what `navigator company --retrieve` returns today: pages)
  2. Ranker.ask on every query of the need, merged by best score (what the people/unit ranker would return)
Writes <out>/<slug>.matches.json and one readable <out>/companies_eval.md, plus near-negative floor checks.
"""
import json
import sys
import time
from collections import Counter
from pathlib import Path

from navigator.answers import CANDIDATES_PER_QUERY, group_by_need
from navigator.rank import Ranker
from navigator.retrieve import load_queries

out_dir = Path(sys.argv[1])
slugs = sys.argv[2:]
out_dir.mkdir(parents=True, exist_ok=True)

ranker = Ranker()
retriever = ranker.r
lines = [f"# Company flow evaluation ({time.strftime('%Y-%m-%d %H:%M')}, index {retriever.meta['index_version']})", ""]
summary_rows = []


def merged_rank(queries: list[str], k: int = 5) -> dict:
    best = {"people": {}, "units": {}}
    floors = []
    for q in queries:
        res = ranker.ask(q, k=15)
        floors.append(res["no_reliable_match"])
        for kind in ("people", "units"):
            for r in res[kind]:
                key = r["keys"][0]
                if key not in best[kind] or r["score"] > best[kind][key]["score"]:
                    best[kind][key] = {**r, "query": q}
    return {kind: sorted(v.values(), key=lambda r: -r["score"])[:k] for kind, v in best.items()} | {
        "all_refused": all(floors), "refused": sum(floors), "n": len(floors)}


for slug in slugs:
    qpath = Path("data/companies") / slug / "queries.json"
    queries = load_queries(str(qpath))
    t0 = time.perf_counter()
    m = retriever.retrieve(queries, threshold=0.0, top_k=CANDIDATES_PER_QUERY)
    m["by_need"] = group_by_need(queries, m)
    (out_dir / f"{slug}.matches.json").write_text(json.dumps(m, indent=1, ensure_ascii=False), encoding="utf-8")
    c = queries["company"]
    conf = Counter(g["confidence"] for g in m["by_need"])
    lines += [f"## {c['name']}  ({slug})", "",
              f"{c.get('summary', '')}", "",
              f"sector: {c.get('sector')} · stage: {c.get('stage')} · in Bern: {c.get('in_bern')} · "
              f"generated by: {queries.get('generated_by')} · ties: {queries.get('ties', {}).get('count', '–')} pages · "
              f"needs: {len(queries['needs'])} · queries: {len(queries['queries'])} · "
              f"confidence: {dict(conf)}", ""]
    sites_all = Counter()
    for g in m["by_need"]:
        need = next(n for n in queries["needs"] if n["id"] == g["id"])
        qtexts = [q["text"] for q in queries["queries"] if q["need_id"] == g["id"]]
        rk = merged_rank(qtexts)
        lines += [f"### {g['id']} · {g['section']} {g['section_name']} — **{g['confidence']}** "
                  f"(margin {g['margin']:+.2f} z, coverage {g['coverage']})",
                  f"Q: {g['question']}", ""]
        for q in qtexts:
            lines.append(f"- `q` {q}")
        lines.append("")
        lines.append("Pages (answers.select):")
        for h in g["hits"]:
            sites_all[h["source_id"]] += 1
            snip = h["text"].split("\n", 1)[-1][:140].replace("\n", " ")
            lines.append(f"  - {h['margin']:+.2f} `{h['source_id']}` [{h['title'][:70]}]({h['url']}) — {snip}")
        lines.append(f"\nRanker people (floor refused {rk['refused']}/{rk['n']} queries):")
        for r in rk["people"]:
            role = " · ".join(x for x in [r.get("role"), r.get("group")] if x)[:80]
            lines.append(f"  - {r['score']:.3f} {r['name']} ({role}) `{r['source_id']}` via {r['via']['how']}")
        lines.append("Ranker units:")
        for r in rk["units"]:
            lines.append(f"  - {r['score']:.3f} {r['name']} `{r['source_id']}` via {r['via']['how']}")
        lines.append("")
        summary_rows.append({"company": slug, "need": g["id"], "section": g["section"], "confidence": g["confidence"],
                             "margin": g["margin"], "n_hits": len(g["hits"]),
                             "top_site": g["hits"][0]["source_id"] if g["hits"] else None,
                             "top_score_raw": g["hits"][0]["score_raw"] if g["hits"] else None,
                             "ranker_best_person": rk["people"][0]["score"] if rk["people"] else None,
                             "ranker_all_refused": rk["all_refused"]})
    lines += [f"_Sites across all answers: {dict(sites_all.most_common(8))} · {time.perf_counter() - t0:.1f}s_", ""]
    print(f"{slug}: {dict(conf)}", flush=True)

# near-negatives from the agents' handoff: best score vs the 0.85 floor
nn_path = Path(sys.argv[0]).parent / "near_negatives.jsonl"
if nn_path.exists():
    lines += ["## Near-negative queries vs floor", "", "| query | best | refused at 0.85 |", "|---|---|---|"]
    for l in open(nn_path, encoding="utf-8"):
        q = json.loads(l)["query"]
        res = ranker.ask(q, k=3)
        top = (res["people"] + res["units"])[:1]
        lines.append(f"| {q} | {res['best_score']:.3f} | {res['no_reliable_match']} |")
        summary_rows.append({"near_negative": q, "best": res["best_score"], "refused": res["no_reliable_match"],
                             "top": top[0]["name"] if top else None})

(out_dir / "companies_eval.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
(out_dir / "companies_eval.json").write_text(json.dumps(summary_rows, indent=1, ensure_ascii=False), encoding="utf-8")
print("wrote", out_dir / "companies_eval.md")
